import { useState } from "react";
import { useQuery, useMutation } from "@tanstack/react-query";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle, DialogTrigger } from "@/components/ui/dialog";
import { Form, FormControl, FormField, FormItem, FormLabel, FormMessage } from "@/components/ui/form";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { useEntityContext } from "@/hooks/useEntityContext";
import { useToast } from "@/hooks/use-toast";
import { useForm } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import { z } from "zod";
import { apiRequest, queryClient } from "@/lib/queryClient";
import { format, isAfter, isBefore, startOfDay, endOfDay, addDays } from "date-fns";

const deadlineSchema = z.object({
  title: z.string().min(1, "Title is required"),
  description: z.string().optional(),
  dueDate: z.date(),
  category: z.string().min(1, "Category is required"),
  priority: z.enum(["low", "medium", "high", "critical"]),
});

type DeadlineFormData = z.infer<typeof deadlineSchema>;

interface ComplianceDeadline {
  id: string;
  title: string;
  description?: string;
  dueDate: string;
  category: string;
  priority: "low" | "medium" | "high" | "critical";
  status: "pending" | "completed" | "overdue";
  isAutoGenerated: boolean;
  reminderSent: boolean;
  createdAt: string;
}

export function ComplianceCalendar() {
  const { currentEntity } = useEntityContext();
  const { toast } = useToast();
  const [viewMode, setViewMode] = useState<"upcoming" | "overdue" | "all">("upcoming");
  const [isAddDialogOpen, setIsAddDialogOpen] = useState(false);

  const form = useForm<DeadlineFormData>({
    resolver: zodResolver(deadlineSchema),
    defaultValues: {
      title: "",
      description: "",
      dueDate: new Date(),
      category: "",
      priority: "medium",
    },
  });

  const { data: deadlines, isLoading } = useQuery<ComplianceDeadline[]>({
    queryKey: ['/api/compliance/deadlines', currentEntity?.id],
    enabled: !!currentEntity?.id,
  });

  const addDeadlineMutation = useMutation({
    mutationFn: (data: DeadlineFormData) => apiRequest(`/api/compliance/deadlines`, "POST", {
      ...data,
      orgId: currentEntity?.id,
    }),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['/api/compliance/deadlines'] });
      setIsAddDialogOpen(false);
      form.reset();
      toast({
        title: "Deadline Added",
        description: "Compliance deadline has been added to your calendar.",
      });
    },
    onError: () => {
      toast({
        title: "Error",
        description: "Failed to add deadline. Please try again.",
        variant: "destructive",
      });
    },
  });

  const completeDeadlineMutation = useMutation({
    mutationFn: (deadlineId: string) => apiRequest(`/api/compliance/deadlines/${deadlineId}/complete`, "PATCH"),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['/api/compliance/deadlines'] });
      toast({
        title: "Deadline Completed",
        description: "Deadline marked as completed.",
      });
    },
  });

  const exportCalendarMutation = useMutation<{ downloadUrl: string }, Error, "google" | "outlook">({
    mutationFn: async (format: "google" | "outlook") => {
      const response = await apiRequest(`/api/compliance/deadlines/export/${format}`, "POST", { orgId: currentEntity?.id });
      return response as unknown as { downloadUrl: string };
    },
    onSuccess: (data: { downloadUrl: string }) => {
      window.open(data.downloadUrl, '_blank');
      toast({
        title: "Calendar Exported",
        description: "Calendar file has been generated and downloaded.",
      });
    },
    onError: () => {
      toast({
        title: "Export Failed",
        description: "Failed to export calendar. Please try again.",
        variant: "destructive",
      });
    },
  });

  if (!currentEntity) {
    return (
      <div className="p-6">
        <Card>
          <CardContent className="pt-6">
            <div className="text-center text-muted-foreground">
              Please select an entity to view compliance calendar.
            </div>
          </CardContent>
        </Card>
      </div>
    );
  }

  const getPriorityColor = (priority: string) => {
    switch (priority) {
      case "critical": return "destructive";
      case "high": return "destructive";
      case "medium": return "secondary";
      case "low": return "outline";
      default: return "outline";
    }
  };

  const getStatusColor = (status: string, dueDate: string) => {
    const today = startOfDay(new Date());
    const due = startOfDay(new Date(dueDate));
    
    if (status === "completed") return "text-green-600";
    if (isBefore(due, today)) return "text-red-600";
    if (isBefore(due, addDays(today, 7))) return "text-yellow-600";
    return "text-blue-600";
  };

  const getFilteredDeadlines = () => {
    if (!deadlines) return [];
    
    const today = startOfDay(new Date());
    
    switch (viewMode) {
      case "upcoming":
        return deadlines.filter((d: ComplianceDeadline) => 
          d.status !== "completed" && !isBefore(startOfDay(new Date(d.dueDate)), today)
        );
      case "overdue":
        return deadlines.filter((d: ComplianceDeadline) => 
          d.status !== "completed" && isBefore(startOfDay(new Date(d.dueDate)), today)
        );
      case "all":
      default:
        return deadlines;
    }
  };

  const filteredDeadlines = getFilteredDeadlines();
  const upcomingCount = deadlines?.filter((d: ComplianceDeadline) => 
    d.status !== "completed" && !isBefore(startOfDay(new Date(d.dueDate)), startOfDay(new Date()))
  ).length || 0;
  const overdueCount = deadlines?.filter((d: ComplianceDeadline) => 
    d.status !== "completed" && isBefore(startOfDay(new Date(d.dueDate)), startOfDay(new Date()))
  ).length || 0;

  const onSubmit = (data: DeadlineFormData) => {
    addDeadlineMutation.mutate(data);
  };

  return (
    <div className="p-6 space-y-6">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-2xl font-semibold">Compliance Calendar</h1>
          <p className="text-muted-foreground">
            Track filing deadlines and meeting requirements for {currentEntity.name}
          </p>
        </div>
        <div className="flex items-center gap-2">
          <Button
            variant="outline"
            onClick={() => exportCalendarMutation.mutate("google")}
            disabled={exportCalendarMutation.isPending}
            data-testid="export-google-calendar"
          >
            <i className="fab fa-google mr-2"></i>
            Export to Google
          </Button>
          <Button
            variant="outline"
            onClick={() => exportCalendarMutation.mutate("outlook")}
            disabled={exportCalendarMutation.isPending}
            data-testid="export-outlook-calendar"
          >
            <i className="fab fa-microsoft mr-2"></i>
            Export to Outlook
          </Button>
          <Dialog open={isAddDialogOpen} onOpenChange={setIsAddDialogOpen}>
            <DialogTrigger asChild>
              <Button data-testid="add-deadline-button">
                <i className="fas fa-plus mr-2"></i>
                Add Deadline
              </Button>
            </DialogTrigger>
            <DialogContent>
              <DialogHeader>
                <DialogTitle>Add Compliance Deadline</DialogTitle>
                <DialogDescription>
                  Create a new compliance deadline or filing requirement.
                </DialogDescription>
              </DialogHeader>
              <Form {...form}>
                <form onSubmit={form.handleSubmit(onSubmit)} className="space-y-4">
                  <FormField
                    control={form.control}
                    name="title"
                    render={({ field }) => (
                      <FormItem>
                        <FormLabel>Title</FormLabel>
                        <FormControl>
                          <Input {...field} placeholder="Annual return filing" data-testid="input-deadline-title" />
                        </FormControl>
                        <FormMessage />
                      </FormItem>
                    )}
                  />
                  <FormField
                    control={form.control}
                    name="description"
                    render={({ field }) => (
                      <FormItem>
                        <FormLabel>Description (Optional)</FormLabel>
                        <FormControl>
                          <Textarea {...field} placeholder="Additional details..." data-testid="textarea-deadline-description" />
                        </FormControl>
                        <FormMessage />
                      </FormItem>
                    )}
                  />
                  <div className="grid grid-cols-2 gap-4">
                    <FormField
                      control={form.control}
                      name="dueDate"
                      render={({ field }) => (
                        <FormItem>
                          <FormLabel>Due Date</FormLabel>
                          <FormControl>
                            <Input
                              type="date"
                              {...field}
                              value={field.value ? format(field.value, 'yyyy-MM-dd') : ''}
                              onChange={(e) => field.onChange(e.target.value ? new Date(e.target.value) : undefined)}
                              data-testid="input-deadline-due-date"
                            />
                          </FormControl>
                          <FormMessage />
                        </FormItem>
                      )}
                    />
                    <FormField
                      control={form.control}
                      name="priority"
                      render={({ field }) => (
                        <FormItem>
                          <FormLabel>Priority</FormLabel>
                          <Select onValueChange={field.onChange} value={field.value}>
                            <FormControl>
                              <SelectTrigger data-testid="select-deadline-priority">
                                <SelectValue placeholder="Select priority" />
                              </SelectTrigger>
                            </FormControl>
                            <SelectContent>
                              <SelectItem value="low">Low</SelectItem>
                              <SelectItem value="medium">Medium</SelectItem>
                              <SelectItem value="high">High</SelectItem>
                              <SelectItem value="critical">Critical</SelectItem>
                            </SelectContent>
                          </Select>
                          <FormMessage />
                        </FormItem>
                      )}
                    />
                  </div>
                  <FormField
                    control={form.control}
                    name="category"
                    render={({ field }) => (
                      <FormItem>
                        <FormLabel>Category</FormLabel>
                        <Select onValueChange={field.onChange} value={field.value}>
                          <FormControl>
                            <SelectTrigger data-testid="select-deadline-category">
                              <SelectValue placeholder="Select category" />
                            </SelectTrigger>
                          </FormControl>
                          <SelectContent>
                            <SelectItem value="annual-return">Annual Return</SelectItem>
                            <SelectItem value="board-meeting">Board Meeting</SelectItem>
                            <SelectItem value="shareholder-meeting">Shareholder Meeting</SelectItem>
                            <SelectItem value="tax-filing">Tax Filing</SelectItem>
                            <SelectItem value="regulatory-filing">Regulatory Filing</SelectItem>
                            <SelectItem value="compliance-review">Compliance Review</SelectItem>
                            <SelectItem value="other">Other</SelectItem>
                          </SelectContent>
                        </Select>
                        <FormMessage />
                      </FormItem>
                    )}
                  />
                  <DialogFooter>
                    <Button
                      type="button"
                      variant="outline"
                      onClick={() => setIsAddDialogOpen(false)}
                    >
                      Cancel
                    </Button>
                    <Button
                      type="submit"
                      disabled={addDeadlineMutation.isPending}
                      data-testid="submit-deadline-form"
                    >
                      {addDeadlineMutation.isPending ? "Adding..." : "Add Deadline"}
                    </Button>
                  </DialogFooter>
                </form>
              </Form>
            </DialogContent>
          </Dialog>
        </div>
      </div>

      {/* Summary Cards */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
        <Card className="cursor-pointer" onClick={() => setViewMode("upcoming")}>
          <CardContent className="pt-4">
            <div className="flex items-center justify-between">
              <div>
                <p className="text-sm text-muted-foreground">Upcoming Deadlines</p>
                <p className="text-2xl font-bold text-blue-600">{upcomingCount}</p>
              </div>
              <i className="fas fa-calendar-alt text-2xl text-blue-500"></i>
            </div>
          </CardContent>
        </Card>

        <Card className="cursor-pointer" onClick={() => setViewMode("overdue")}>
          <CardContent className="pt-4">
            <div className="flex items-center justify-between">
              <div>
                <p className="text-sm text-muted-foreground">Overdue Items</p>
                <p className="text-2xl font-bold text-red-600">{overdueCount}</p>
              </div>
              <i className="fas fa-exclamation-triangle text-2xl text-red-500"></i>
            </div>
          </CardContent>
        </Card>

        <Card className="cursor-pointer" onClick={() => setViewMode("all")}>
          <CardContent className="pt-4">
            <div className="flex items-center justify-between">
              <div>
                <p className="text-sm text-muted-foreground">Total Deadlines</p>
                <p className="text-2xl font-bold">{deadlines?.length || 0}</p>
              </div>
              <i className="fas fa-list text-2xl text-purple-500"></i>
            </div>
          </CardContent>
        </Card>
      </div>

      {/* View Mode Tabs */}
      <div className="flex items-center gap-2">
        {[
          { key: "upcoming", label: "Upcoming", icon: "fas fa-clock" },
          { key: "overdue", label: "Overdue", icon: "fas fa-exclamation-triangle" },
          { key: "all", label: "All", icon: "fas fa-list" },
        ].map((mode) => (
          <Button
            key={mode.key}
            variant={viewMode === mode.key ? "default" : "outline"}
            size="sm"
            onClick={() => setViewMode(mode.key as any)}
            data-testid={`view-mode-${mode.key}`}
          >
            <i className={`${mode.icon} mr-2`}></i>
            {mode.label}
          </Button>
        ))}
      </div>

      {/* Deadlines List */}
      <Card>
        <CardHeader>
          <CardTitle>
            {viewMode === "upcoming" ? "Upcoming Deadlines" :
             viewMode === "overdue" ? "Overdue Items" : "All Deadlines"}
          </CardTitle>
          <CardDescription>
            Manage your compliance deadlines and filing requirements
          </CardDescription>
        </CardHeader>
        <CardContent>
          {isLoading ? (
            <div className="text-center py-8">
              <i className="fas fa-spinner fa-spin text-2xl text-muted-foreground mb-4"></i>
              <p className="text-muted-foreground">Loading deadlines...</p>
            </div>
          ) : filteredDeadlines.length === 0 ? (
            <div className="text-center py-8 text-muted-foreground">
              {viewMode === "upcoming" ? "No upcoming deadlines." :
               viewMode === "overdue" ? "No overdue items! 🎉" : "No deadlines found."}
            </div>
          ) : (
            <div className="space-y-4">
              {filteredDeadlines.map((deadline: ComplianceDeadline) => (
                <Card key={deadline.id} className="border-l-4 border-l-blue-400">
                  <CardContent className="pt-4">
                    <div className="flex items-start justify-between">
                      <div className="flex-1 space-y-2">
                        <div className="flex items-center gap-2">
                          <h4 className="font-medium">{deadline.title}</h4>
                          <Badge variant={getPriorityColor(deadline.priority) as any}>
                            {deadline.priority.toUpperCase()}
                          </Badge>
                          {deadline.isAutoGenerated && (
                            <Badge variant="outline">
                              <i className="fas fa-robot mr-1"></i>
                              AI Generated
                            </Badge>
                          )}
                        </div>
                        {deadline.description && (
                          <p className="text-sm text-muted-foreground">{deadline.description}</p>
                        )}
                        <div className="flex items-center gap-4 text-sm text-muted-foreground">
                          <span className="flex items-center gap-1">
                            <i className="fas fa-calendar"></i>
                            Due: {format(new Date(deadline.dueDate), 'MMM dd, yyyy')}
                          </span>
                          <span className="flex items-center gap-1 capitalize">
                            <i className="fas fa-tag"></i>
                            {deadline.category.replace('-', ' ')}
                          </span>
                          <span className={`flex items-center gap-1 capitalize ${getStatusColor(deadline.status, deadline.dueDate)}`}>
                            <i className="fas fa-circle text-xs"></i>
                            {deadline.status}
                          </span>
                        </div>
                      </div>
                      <div className="flex items-center gap-2">
                        {deadline.status !== "completed" && (
                          <Button
                            size="sm"
                            variant="outline"
                            onClick={() => completeDeadlineMutation.mutate(deadline.id)}
                            disabled={completeDeadlineMutation.isPending}
                            data-testid={`complete-deadline-${deadline.id}`}
                          >
                            <i className="fas fa-check mr-1"></i>
                            Complete
                          </Button>
                        )}
                      </div>
                    </div>
                  </CardContent>
                </Card>
              ))}
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  );
}